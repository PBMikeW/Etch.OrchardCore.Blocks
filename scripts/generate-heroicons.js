const fs = require('fs');
const path = require('path');

// Heroicons ship as one file per icon. The editor needs every icon at once (the
// picker searches all of them) and the site needs them at render time, so this
// builds two artefacts from the package:
//
//  1. wwwroot/assets/heroicons.svg — an external <symbol> sprite. Both the
//     picker preview and the public pages reference it as
//     <svg><use href="…/heroicons.svg#o-name"/></svg>, so the icon bytes are
//     fetched once, cached by the browser, and never inlined into content.
//     wwwroot/ is gitignored and dockerignored; the image build copies the
//     node-build stage's wwwroot/, and turbo's build outputs already list
//     wwwroot/assets/** so a cache hit still restores it.
//
//  2. Assets/…/utils/heroiconsNames.js — just the names, for the picker's
//     search list. 5 KB instead of the 181 KB of inline SVG this replaced.
//
// 24px outline and solid only: those are the two styles the picker offers, and
// the 16/20px sets would double the sprite for sizes nothing renders.

const packageDir = path.resolve(__dirname, '../node_modules/heroicons');

const STYLES = [
  { style: 'outline', prefix: 'o', dir: '24/outline' },
  { style: 'solid', prefix: 's', dir: '24/solid' },
];

const spritePath = path.resolve(__dirname, '../wwwroot/assets/heroicons.svg');
const namesPath = path.resolve(
  __dirname,
  '../Assets/Editor.js/js/plugins/utils/heroiconsNames.js'
);

if (!fs.existsSync(packageDir)) {
  console.error('heroicons not found — run pnpm install first');
  process.exit(1);
}

// Cache-busting stamp for the sprite URL. The package version changes exactly
// when the sprite's contents can change, so it is the right key; the date is a
// fallback for a package.json this cannot read, and only makes the URL change
// more often than it needs to.
const readPackageVersion = () => {
  try {
    const meta = JSON.parse(
      fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8')
    );
    if (meta.version) {
      return meta.version;
    }
  } catch (err) {
    console.warn(`could not read the heroicons version (${err.message})`);
  }

  return new Date().toISOString().slice(0, 10);
};

const version = readPackageVersion();

const readNames = dir => {
  const full = path.join(packageDir, dir);

  // A heroicons release that moves or renames a style directory would
  // otherwise surface as a bare ENOENT from readdirSync, naming a path but not
  // what the build wanted from it.
  if (!fs.existsSync(full)) {
    console.error(
      `heroicons has no ${dir} directory (looked in ${full}) — the package ` +
        'layout changed; update STYLES in scripts/generate-heroicons.js'
    );
    process.exit(1);
  }

  return fs
    .readdirSync(full)
    .filter(f => f.endsWith('.svg'))
    .map(f => f.replace('.svg', ''))
    .sort();
};

const outlineNames = readNames(STYLES[0].dir);
const solidNames = readNames(STYLES[1].dir);

// The picker offers one name list and a style toggle, so a name present in only
// one style would render an empty <use>. Fail the build rather than ship that.
const outlineOnly = outlineNames.filter(n => !solidNames.includes(n));
const solidOnly = solidNames.filter(n => !outlineNames.includes(n));

if (outlineOnly.length || solidOnly.length) {
  console.error(
    'heroicons 24/outline and 24/solid disagree — ' +
      `outline-only: ${outlineOnly.join(', ') || 'none'}; ` +
      `solid-only: ${solidOnly.join(', ') || 'none'}`
  );
  process.exit(1);
}

const toSymbol = (dir, prefix, name, isOutline) => {
  const raw = fs.readFileSync(path.join(packageDir, dir, `${name}.svg`), 'utf8');

  // Keep only what is inside <svg>…</svg>: the per-file xmlns and sizing
  // attributes belong to a standalone document, not to a symbol in a sprite.
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();

  // Paint attributes live on the symbol so currentColor resolves against the
  // <use> element — the icon then takes the colour of whatever text it sits in.
  const paint = isOutline
    ? 'fill="none" stroke="currentColor" stroke-width="1.5"'
    : 'fill="currentColor"';

  return `<symbol id="${prefix}-${name}" viewBox="0 0 24 24" ${paint}>${inner}</symbol>`;
};

const symbols = [];

for (const { prefix, dir } of STYLES) {
  const isOutline = prefix === STYLES[0].prefix;

  for (const name of outlineNames) {
    symbols.push(toSymbol(dir, prefix, name, isOutline));
  }
}

// xmlns is required on the root: this is a standalone document fetched by URL,
// not markup pasted into an HTML page.
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>`;

fs.mkdirSync(path.dirname(spritePath), { recursive: true });
fs.writeFileSync(spritePath, sprite, 'utf8');

const namesOutput = `// Auto-generated by scripts/generate-heroicons.js — do not edit
const HEROICON_NAMES = ${JSON.stringify(outlineNames)};

// Version of the heroicons package these names and the sprite came from. The
// editor stamps it on the sprite URL (utils/heroiconsIndex.js) so an upgraded
// icon set is not served from a stale browser cache.
export const version = '${version}';

export default HEROICON_NAMES;
`;

fs.mkdirSync(path.dirname(namesPath), { recursive: true });
fs.writeFileSync(namesPath, namesOutput, 'utf8');

const kb = bytes => `${(bytes / 1024).toFixed(1)} KB`;

console.log(
  `Generated ${symbols.length} heroicon symbols from heroicons ${version} ` +
    `(${outlineNames.length} names x ${STYLES.length} styles), ` +
    `${kb(Buffer.byteLength(sprite))} -> ${spritePath}`
);
console.log(
  `Generated ${outlineNames.length} heroicon names, ` +
    `${kb(Buffer.byteLength(namesOutput))} -> ${namesPath}`
);
